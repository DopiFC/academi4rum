create or replace function public.tags_to_text(text[])
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$ select pg_catalog.array_to_string($1, ' ') $$;

create table if not exists public.posts (
  id uuid primary key default gen_random_uuid(),
  author_id uuid not null references public.profiles(id) on delete cascade,
  category_id bigint not null references public.categories(id) on delete restrict,
  post_type text not null default 'discussion' check (post_type in ('question', 'knowledge', 'resource', 'discussion')),
  tags text[] not null default '{}' check (cardinality(tags) <= 10),
  title text not null check (char_length(btrim(title)) between 10 and 180),
  content text not null check (char_length(btrim(content)) between 1 and 30000),
  status text not null default 'published' check (status in ('published', 'hidden')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  comment_count integer not null default 0 check (comment_count >= 0),
  reaction_count integer not null default 0 check (reaction_count >= 0),
  vote_count integer not null default 0 check (vote_count >= 0),
  search_document tsvector generated always as (
    to_tsvector('simple'::regconfig, coalesce(title, '') || ' ' || coalesce(content, '') || ' ' || public.tags_to_text(tags))
  ) stored
);

