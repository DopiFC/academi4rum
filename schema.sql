create or replace function public.provision_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  display_value text;
begin
  display_value := nullif(btrim(coalesce(new.raw_user_meta_data ->> 'display_name', '')), '');
  if display_value is null or char_length(display_value) < 2 then
    display_value := 'Thành viên';
  end if;
  insert into public.profiles (id, display_name)
  values (new.id, left(display_value, 60));
  insert into public.user_roles (user_id, role) values (new.id, 'member');
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.provision_new_user();

insert into public.profiles (id, display_name)
select
  u.id,
  left(
