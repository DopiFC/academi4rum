create or replace function public.notify_post_comment()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  post_author uuid;
  parent_author uuid;
begin
  select author_id into post_author from public.posts where id = new.post_id;
  if new.parent_id is not null then
    select author_id into parent_author from public.comments where id = new.parent_id;
  end if;
  if new.parent_id is not null and parent_author is distinct from new.author_id then
    insert into public.notifications (recipient_id, actor_id, kind, post_id, comment_id)
    values (parent_author, new.author_id, 'reply', new.post_id, new.id);
  elsif post_author is distinct from new.author_id then
    insert into public.notifications (recipient_id, actor_id, kind, post_id, comment_id)
    values (post_author, new.author_id, 'comment', new.post_id, new.id);
  end if;
  return new;
end;
$$;

drop trigger if exists notify_post_comment on public.comments;
create trigger notify_post_comment
  after insert on public.comments
  for each row execute function public.notify_post_comment();

